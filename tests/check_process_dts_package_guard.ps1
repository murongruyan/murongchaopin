param(
    [string]$Repo = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem

$packScript = Join-Path $Repo 'packaging/build_module_zip.ps1'
$tempParent = [System.IO.Path]::GetTempPath()
$tempRoot = Join-Path $tempParent ('murong-process-dts-package-' + [Guid]::NewGuid().ToString('N'))
$utf8 = New-Object System.Text.UTF8Encoding($false)
$originalTemp = $env:TEMP

function Write-FixtureFile([string]$Root, [string]$RelativePath, [string]$Text) {
    $path = Join-Path $Root $RelativePath
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    [System.IO.File]::WriteAllText($path, $Text, $utf8)
}

function New-Fixture([string]$Name) {
    $root = Join-Path $tempRoot $Name
    # CRLF intentionally differs from the LF fingerprint generated by CI.
    Write-FixtureFile $root 'src/process_dts.c' "// fixture`r`n"
    Write-FixtureFile $root 'bin/process_dts' 'fixture process_dts binary'
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $digest = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes("// fixture`n"))
    } finally {
        $sha.Dispose()
    }
    $hex = ($digest | ForEach-Object { $_.ToString('x2') }) -join ''
    Write-FixtureFile $root 'bin/process_dts.src.sha256' "$hex  process_dts.c`n"
    return $root
}

function Assert-Rejected([string]$Root, [string]$ExpectedMessage) {
    $message = ''
    try {
        & $packScript -Repo $Root | Out-Null
    } catch {
        $message = $_.Exception.Message
    }
    if ($message -notlike "*$ExpectedMessage*") {
        throw "Expected '$ExpectedMessage', got '$message'"
    }
    if (Test-Path -LiteralPath (Join-Path $Root 'work')) {
        throw 'Invalid process_dts build reached staging before rejection'
    }
}

try {
    New-Item -ItemType Directory -Path $tempRoot | Out-Null
    # The local packager also uses TEMP for its APK inspection on Linux CI.
    $env:TEMP = $tempRoot

    $fixture = New-Fixture 'missing-binary'
    Remove-Item -LiteralPath (Join-Path $fixture 'bin/process_dts')
    Assert-Rejected $fixture 'missing non-empty process_dts build input'

    $fixture = New-Fixture 'empty-binary'
    Write-FixtureFile $fixture 'bin/process_dts' ''
    Assert-Rejected $fixture 'missing non-empty process_dts build input'

    $fixture = New-Fixture 'missing-sidecar'
    Remove-Item -LiteralPath (Join-Path $fixture 'bin/process_dts.src.sha256')
    Assert-Rejected $fixture 'missing non-empty process_dts build input'

    $fixture = New-Fixture 'malformed-sidecar'
    Write-FixtureFile $fixture 'bin/process_dts.src.sha256' "not-a-hash  process_dts.c`n"
    Assert-Rejected $fixture 'malformed process_dts source fingerprint'

    $fixture = New-Fixture 'stale-sidecar'
    Write-FixtureFile $fixture 'bin/process_dts.src.sha256' (('0' * 64) + "  process_dts.c`n")
    Assert-Rejected $fixture 'process_dts was built from an older src/process_dts.c'

    $fixture = New-Fixture 'valid-crlf-source'
    foreach ($name in @('action.sh', 'customize.sh', 'post-fs-data.sh', 'post-mount.sh',
            'late-load.sh', 'service.sh', 'uninstall.sh', 'KsuWebUI.apk',
            'bin/ko_abi_guard', 'bin/display_settings_hook.apk.idsig', 'bin/curl',
            'bin/lib64/libcrypto.so', 'bin/lib64/libssl.so', 'bin/lib64/libz.so',
            'bin/lib64/libc++.so', 'bin/process_dts.test',
            'bin/libpwirisservicei7p.rmx5200.memc-gate.c17.so',
            'bin/plq110_adfr_lock.ko')) {
        Write-FixtureFile $fixture $name 'fixture'
    }
    Write-FixtureFile $fixture 'module.prop' "id=fixture`nversion=0.0-test`n"
    $hookPath = Join-Path $fixture 'bin/display_settings_hook.apk'
    $hook = [System.IO.Compression.ZipFile]::Open($hookPath, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
        $hook.CreateEntry('classes.dex') | Out-Null
    } finally {
        $hook.Dispose()
    }
    & $packScript -Repo $fixture | Out-Null
    $zipFile = @(Get-ChildItem -LiteralPath (Join-Path $fixture 'work') -Filter '*.zip')
    if ($zipFile.Count -ne 1) { throw 'Valid source fingerprint did not produce one fixture ZIP' }
    $zip = [System.IO.Compression.ZipFile]::OpenRead($zipFile[0].FullName)
    try {
        $names = @($zip.Entries | ForEach-Object { $_.FullName })
        if ('bin/process_dts.src.sha256' -notin $names) { throw 'Source fingerprint was removed from ZIP' }
        if ('bin/process_dts.test' -in $names) { throw 'Development process_dts variant leaked into ZIP' }
        if ('bin/libpwirisservicei7p.rmx5200.memc-gate.c17.so' -in $names) { throw 'Paid MEMC firmware variant leaked into ZIP' }
        if ('bin/plq110_adfr_lock.ko' -in $names) { throw 'Paid ADFR model variant leaked into ZIP' }
    } finally {
        $zip.Dispose()
    }
    Write-Host 'PASS: process_dts package guard rejects missing, empty, malformed and stale builds; LF/CRLF and sidecar preservation verified'
} finally {
    $env:TEMP = $originalTemp
    if (Test-Path -LiteralPath $tempRoot) {
        $resolvedTempRoot = (Resolve-Path -LiteralPath $tempRoot).Path
        $resolvedTempParent = (Resolve-Path -LiteralPath $tempParent).Path.TrimEnd('\', '/')
        $prefix = $resolvedTempParent + [System.IO.Path]::DirectorySeparatorChar
        if (-not $resolvedTempRoot.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase) -or
            (Split-Path -Leaf $resolvedTempRoot) -notlike 'murong-process-dts-package-*') {
            throw "Refusing to clean unexpected test directory: $resolvedTempRoot"
        }
        Remove-Item -LiteralPath $resolvedTempRoot -Recurse -Force
    }
}
